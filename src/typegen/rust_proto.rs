//! Rust proto conversion generator — `from_document` impls over the typed
//! `FieldValue` / `DataMap` wire messages.
//!
//! Generates `proto.rs` with direct extraction from the generated proto types:
//! no JSON intermediate, no serde deserialization in the hot path.

use crate::core::{
    CollectionDefinition, FieldDefinition, Registry, collection::GlobalDefinition,
    flatten_array_sub_fields,
};

use super::client::{FieldTy, resolve_ty};
use super::helpers::{
    collect_sub_type_fields, is_optional, is_single_ref, sorted_collection_slugs,
    sorted_global_slugs, to_pascal_case, w, wraw,
};
use super::idents;

/// Render proto conversion code for all collections and globals.
pub(super) fn render(registry: &Registry, proto_mod: &str) -> String {
    let mut out = String::new();

    w!(out, "// Auto-generated by crap-cms. Do not edit.");
    w!(out, "//");
    w!(
        out,
        "// Proto-to-struct conversion over the typed FieldValue/DataMap messages."
    );
    w!(
        out,
        "// Import the generated structs from generated.rs alongside this file."
    );
    w!(out, "");
    w!(out, "use {}::field_value::Kind;", proto_mod);
    w!(out, "use {}::{{DataMap, Document}};", proto_mod);
    w!(out, "");
    w!(out, "use super::generated::*;");
    w!(out, "");

    render_from_document_trait(&mut out);
    render_helpers(&mut out);
    render_rel_helpers(&mut out);

    for slug in sorted_collection_slugs(registry) {
        let col = &registry.collections[slug];
        render_collection_impl(&mut out, col);
    }

    for slug in sorted_global_slugs(registry) {
        let global = &registry.globals[slug];
        render_global_impl(&mut out, global);
    }

    out
}

/// Render the numeric getters. A number field arrives as `IntValue` (integers,
/// exact) or `DoubleValue` (fractional); both collapse to `f64`.
fn render_num_helpers(out: &mut String) {
    w!(out, "fn get_num(doc: &Document, name: &str) -> f64 {{");
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(
        out,
        "            Some(Kind::IntValue(n)) => Some(*n as f64),"
    );
    w!(out, "            Some(Kind::DoubleValue(n)) => Some(*n),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "        .unwrap_or(0.0)");
    w!(out, "}}");
    w!(out, "");
    w!(
        out,
        "fn get_num_opt(doc: &Document, name: &str) -> Option<f64> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(
        out,
        "            Some(Kind::IntValue(n)) => Some(*n as f64),"
    );
    w!(out, "            Some(Kind::DoubleValue(n)) => Some(*n),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "}}");
    w!(out, "");
}

