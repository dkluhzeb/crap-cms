    w!(out, "");
    w!(out, "fn get_str(doc: &Document, name: &str) -> String {{");
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
