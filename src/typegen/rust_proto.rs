//! Rust proto conversion generator — `from_document` impls over the typed
//! `FieldValue` / `DataMap` wire messages.
//!
//! Generates `proto.rs` with direct extraction from the generated proto types:
//! no JSON intermediate, no serde deserialization in the hot path.

use crate::core::{
    CollectionDefinition, FieldDefinition, REVISION_COLUMN, Registry,
    collection::GlobalDefinition,
    flatten_array_sub_fields,
    upload::{read_shape_fields, readable_fields},
};

use super::client::{FieldTy, resolve_ty};
use super::helpers::{
    collect_sub_type_fields, sorted_collection_slugs, sorted_global_slugs, to_pascal_case, w, wraw,
};
use super::idents;

/// Render proto conversion code for all collections and globals.
pub(super) fn render(registry: &Registry, proto_mod: &str) -> String {
    let mut out = String::new();

    w!(out, "// Auto-generated by crap-cms. Do not edit.");
    w!(out, "//");
    w!(
        out,
        "// Proto-to-struct conversion over the typed FieldValue/DataMap messages."
    );
    w!(
        out,
        "// Import the generated structs from generated.rs alongside this file."
    );
    w!(out, "");
    w!(out, "use {}::field_value::Kind;", proto_mod);
    w!(out, "use {}::{{DataMap, Document, FieldValue}};", proto_mod);
    w!(out, "");
    w!(out, "use super::generated::*;");
    w!(out, "");

    render_from_document_trait(&mut out);
    render_helpers(&mut out);
    render_json_helpers(&mut out);
    render_rel_helpers(&mut out);

    for slug in sorted_collection_slugs(registry) {
        let col = &registry.collections[slug];
        render_collection_impl(&mut out, col);
    }

    for slug in sorted_global_slugs(registry) {
        let global = &registry.globals[slug];
        render_global_impl(&mut out, global);
    }

    out
}

/// Render the numeric getters. A number field arrives as `IntValue` (integers,
/// exact) or `DoubleValue` (fractional); both collapse to `f64`. The integer
/// getter reads the `_revision` system key, always an `IntValue`.
fn render_num_helpers(out: &mut String) {
    w!(
        out,
        "fn get_num_opt(doc: &Document, name: &str) -> Option<f64> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(
        out,
        "            Some(Kind::IntValue(n)) => Some(*n as f64),"
    );
    w!(out, "            Some(Kind::DoubleValue(n)) => Some(*n),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "}}");
    w!(out, "");
    w!(
        out,
        "fn get_int_opt(doc: &Document, name: &str) -> Option<i64> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(out, "            Some(Kind::IntValue(n)) => Some(*n),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "}}");
    w!(out, "");
}

/// Render shared helper functions for field extraction.
fn render_helpers(out: &mut String) {
    w!(
        out,
        "// ── Extraction helpers ─────────────────────────────────────"
    );
    w!(out, "");
    w!(out, "fn get_str(doc: &Document, name: &str) -> String {{");
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(
        out,
        "            Some(Kind::StringValue(s)) => Some(s.clone()),"
    );
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "        .unwrap_or_default()");
    w!(out, "}}");
    w!(out, "");
    w!(
        out,
        "fn get_str_opt(doc: &Document, name: &str) -> Option<String> {{"
    );
    w!(out, "    let s = get_str(doc, name);");
    w!(out, "    if s.is_empty() {{ None }} else {{ Some(s) }}");
    w!(out, "}}");
    w!(out, "");
    render_num_helpers(out);

    w!(
        out,
        "fn get_bool_opt(doc: &Document, name: &str) -> Option<bool> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(out, "            Some(Kind::BoolValue(b)) => Some(*b),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "}}");
    w!(out, "");
    w!(
        out,
        "fn get_str_list(doc: &Document, name: &str) -> Vec<String> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(out, "            Some(Kind::ListValue(list)) => Some(");
    w!(out, "                list.values.iter()");
    w!(out, "                    .filter_map(|v| match &v.kind {{");
    w!(
        out,
        "                        Some(Kind::StringValue(s)) => Some(s.clone()),"
    );
    w!(out, "                        _ => None,");
    w!(out, "                    }})");
    w!(out, "                    .collect()");
    w!(out, "            ),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "        .unwrap_or_default()");
    w!(out, "}}");
    w!(out, "");

    // Numeric list: a `has_many` number field. Each element is `IntValue`
    // (exact) or `DoubleValue`; both collapse to `f64`, mirroring `get_num_opt`.
    w!(
        out,
        "fn get_num_list(doc: &Document, name: &str) -> Vec<f64> {{"
    );
    w!(out, "    doc.fields.as_ref()");
    w!(out, "        .and_then(|f| f.fields.get(name))");
    w!(out, "        .and_then(|v| match &v.kind {{");
    w!(out, "            Some(Kind::ListValue(list)) => Some(");
    w!(out, "                list.values.iter()");
    w!(out, "                    .filter_map(|v| match &v.kind {{");
    w!(
        out,
        "                        Some(Kind::IntValue(n)) => Some(*n as f64),"
    );
    w!(
        out,
        "                        Some(Kind::DoubleValue(n)) => Some(*n),"
    );
    w!(out, "                        _ => None,");
    w!(out, "                    }})");
    w!(out, "                    .collect()");
    w!(out, "            ),");
    w!(out, "            _ => None,");
    w!(out, "        }})");
    w!(out, "        .unwrap_or_default()");
    w!(out, "}}");
    w!(out, "");
}

/// Render the `FromDocument` trait definition.
fn render_from_document_trait(out: &mut String) {
    w!(
        out,
        "/// Trait for types that can be constructed from a proto Document."
    );
    w!(out, "pub trait FromDocument {{");
    w!(out, "    fn from_document(doc: &Document) -> Self;");
    w!(out, "}}");
    w!(out, "");
}

/// Hand-written Rust helpers (`struct_to_document` + `get_rel` + `get_rel_list`)
/// that the generated `from_document` impls call into. Emitted verbatim — they
/// have no per-collection or per-field interpolation, so a raw literal is the
/// source of truth, not a write-line-by-line chain.
const REL_HELPERS_SOURCE: &str = r#"
// ── Relationship helpers ──────────────────────────────────

fn struct_to_document(s: &DataMap) -> Document {
    let id = s.fields.get("id")
        .and_then(|v| match &v.kind {
            Some(Kind::StringValue(s)) => Some(s.clone()),
            _ => None,
        })
        .unwrap_or_default();

    Document {
        id,
        collection: String::new(),
        fields: Some(DataMap { fields: s.fields.clone() }),
        created_at: s.fields.get("created_at").and_then(|v| match &v.kind {
            Some(Kind::StringValue(s)) => Some(s.clone()),
            _ => None,
        }),
        updated_at: s.fields.get("updated_at").and_then(|v| match &v.kind {
            Some(Kind::StringValue(s)) => Some(s.clone()),
            _ => None,
        }),
    }
}

fn get_rel<T: FromDocument>(doc: &Document, name: &str) -> Option<Rel<T>> {
    doc.fields.as_ref()
        .and_then(|f| f.fields.get(name))
        .and_then(|v| match &v.kind {
            Some(Kind::StringValue(s)) if !s.is_empty() => Some(Rel::Id(s.clone())),
            Some(Kind::StructValue(s)) => {
                let inner = struct_to_document(s);
                Some(Rel::Doc(Box::new(T::from_document(&inner))))
            }
            _ => None,
        })
}

fn get_rel_list<T: FromDocument>(doc: &Document, name: &str) -> Vec<Rel<T>> {
    doc.fields.as_ref()
        .and_then(|f| f.fields.get(name))
        .and_then(|v| match &v.kind {
            Some(Kind::ListValue(list)) => Some(
                list.values.iter()
                    .filter_map(|v| match &v.kind {
                        Some(Kind::StringValue(s)) if !s.is_empty() => Some(Rel::Id(s.clone())),
                        Some(Kind::StructValue(s)) => {
                            let inner = struct_to_document(s);
                            Some(Rel::Doc(Box::new(T::from_document(&inner))))
                        }
                        _ => None,
                    })
                    .collect()
            ),
            _ => None,
        })
        .unwrap_or_default()
}
"#;

/// Render relationship helpers that use `FromDocument` + `Rel<T>`.
fn render_rel_helpers(out: &mut String) {
    out.push_str(REL_HELPERS_SOURCE);
    out.push('\n');
}

/// Hand-written helpers for the wire values that carry no fixed shape: a
/// `json` field, a rich text field stored as a JSON document, an empty group,
/// a blocks or join list. The wire does carry structured JSON — the encoder
/// spells an object as `StructValue` and an array as `ListValue` — so these
/// convert the value instead of dropping it. The recursion is bounded by
/// prost's decode recursion limit, which no decoded message can exceed.
const JSON_HELPERS_SOURCE: &str = r"
// ── JSON helpers ──────────────────────────────────────────

fn field_value_to_json(v: &FieldValue) -> serde_json::Value {
    match &v.kind {
        Some(Kind::BoolValue(b)) => serde_json::Value::Bool(*b),
        Some(Kind::IntValue(n)) => serde_json::Value::from(*n),
        Some(Kind::DoubleValue(n)) => serde_json::Number::from_f64(*n)
            .map_or(serde_json::Value::Null, serde_json::Value::Number),
        Some(Kind::StringValue(s)) => serde_json::Value::String(s.clone()),
        Some(Kind::ListValue(list)) => serde_json::Value::Array(
            list.values.iter().map(field_value_to_json).collect()
        ),
        Some(Kind::StructValue(s)) => serde_json::Value::Object(
            s.fields.iter()
                .map(|(k, v)| (k.clone(), field_value_to_json(v)))
                .collect()
        ),
        Some(Kind::NullValue(_)) | None => serde_json::Value::Null,
    }
}

fn get_json(doc: &Document, name: &str) -> Option<serde_json::Value> {
    doc.fields.as_ref()
        .and_then(|f| f.fields.get(name))
        .map(field_value_to_json)
}

fn get_json_list(doc: &Document, name: &str) -> Option<Vec<serde_json::Value>> {
    doc.fields.as_ref()
        .and_then(|f| f.fields.get(name))
        .and_then(|v| match &v.kind {
            Some(Kind::ListValue(list)) => Some(
                list.values.iter().map(field_value_to_json).collect()
            ),
            _ => None,
        })
}
";

/// Render the JSON-value helpers.
fn render_json_helpers(out: &mut String) {
    out.push_str(JSON_HELPERS_SOURCE);
    out.push('\n');
}

/// Render `from_document` impl for a collection.
fn render_collection_impl(out: &mut String, col: &CollectionDefinition) {
    // Sub-types compose from the raw `PascalCase` base and are sanitized as
    // whole names, exactly as the client names them (`client::driver` +
    // `client::rust`): a reserved owner (`box` → `Box_`) keeps its group
    // `BoxMeta`, not `Box_Meta`.
    let base = to_pascal_case(&col.slug);
    let pascal = idents::rust_type(&base);

    // The READ shape, the same one `client/rust.rs` types the structs from: an
    // upload collection's per-size columns arrive folded into one `sizes`
    // object, never as the stored columns, and hidden fields never arrive.
    let fields = read_shape_fields(col);

    // Sub-type from_struct impls for arrays
    for stf in collect_sub_type_fields(&fields, &base) {
        let sub_pascal = format!("{}{}", stf.parent_pascal, to_pascal_case(&stf.field.name));
        render_sub_type_from_struct(out, &sub_pascal, &stf.field.fields, stf.row_id);
    }

    w!(out, "impl {} {{", pascal);
    w!(out, "    pub fn from_document(doc: &Document) -> Self {{");
    w!(out, "        Self {{");
    w!(out, "            id: doc.id.clone(),");

    render_field_extractions(out, &fields, &base, "doc");
    render_system_extractions(out, col.has_drafts(), col.soft_delete);

    if col.timestamps {
        w!(out, "            created_at: doc.created_at.clone(),");
        w!(out, "            updated_at: doc.updated_at.clone(),");
    }

    w!(out, "        }}");
    w!(out, "    }}");
    w!(out, "}}");
    w!(out, "");
    w!(out, "impl FromDocument for {} {{", pascal);
    w!(out, "    fn from_document(doc: &Document) -> Self {{");
    w!(out, "        {}::from_document(doc)", pascal);
    w!(out, "    }}");
    w!(out, "}}");
    w!(out, "");
}

/// Render `from_document` impl for a global.
fn render_global_impl(out: &mut String, global: &GlobalDefinition) {
    // Sub-types compose from the raw base, as in `render_collection_impl`.
    let base = to_pascal_case(&global.slug);
    let pascal = idents::rust_type(&base);

    // The READ shape, the same one `client/rust.rs` types the struct from:
    // hidden fields never reach a reader.
    let fields = readable_fields(&global.fields);

    for stf in collect_sub_type_fields(&fields, &base) {
        let sub_pascal = format!("{}{}", stf.parent_pascal, to_pascal_case(&stf.field.name));
        render_sub_type_from_struct(out, &sub_pascal, &stf.field.fields, stf.row_id);
    }

    w!(out, "impl {} {{", pascal);
    w!(out, "    pub fn from_document(doc: &Document) -> Self {{");
    w!(out, "        Self {{");
    w!(out, "            id: doc.id.clone(),");

    render_field_extractions(out, &fields, &base, "doc");
    render_system_extractions(out, global.has_drafts(), false);

    w!(out, "            created_at: doc.created_at.clone(),");
    w!(out, "            updated_at: doc.updated_at.clone(),");
    w!(out, "        }}");
    w!(out, "    }}");
    w!(out, "}}");
    w!(out, "");
    w!(out, "impl FromDocument for {} {{", pascal);
    w!(out, "    fn from_document(doc: &Document) -> Self {{");
    w!(out, "        {}::from_document(doc)", pascal);
    w!(out, "    }}");
    w!(out, "}}");
    w!(out, "");
}

/// Render field extraction lines for a struct's `from_document` body.
/// The canonical wrapper-flatten (`flatten_array_sub_fields`) promotes
/// Row/Collapsible/Tabs sub-fields to this level.
fn render_field_extractions(
    out: &mut String,
    fields: &[FieldDefinition],
    parent_pascal: &str,
    doc_var: &str,
) {
    for f in flatten_array_sub_fields(fields) {
        let extraction = field_extraction(f, parent_pascal, doc_var);
        w!(
            out,
            "            {}: {},",
            idents::rust_field(&f.name).ident,
            extraction
        );

        for column in f.companion_columns(&f.name) {
            let ident = idents::rust_field(&column).ident;
            w!(
                out,
                "            {ident}: get_str_opt({doc_var}, \"{column}\"),"
            );
        }
    }
}

/// Extraction lines for the stored system keys a read document carries: its
/// revision always, `_status` / `_deleted_at` with the features.
fn render_system_extractions(out: &mut String, drafts: bool, soft_delete: bool) {
    w!(
        out,
        "            {REVISION_COLUMN}: get_int_opt(doc, \"{REVISION_COLUMN}\"),"
    );

    for (present, key) in [(drafts, "_status"), (soft_delete, "_deleted_at")] {
        if present {
            w!(out, "            {key}: get_str_opt(doc, \"{key}\"),");
        }
    }
}

/// A list extraction, `None` when the list is empty.
fn opt_list(expr: &str, doc_var: &str, name: &str) -> String {
    format!(
        "{{ let v = {expr}({doc_var}, \"{name}\"); if v.is_empty() {{ None }} else {{ Some(v) }} }}"
    )
}

/// A scalar extraction through the `get_X_opt` getter.
fn scalar(base: &str, doc_var: &str, name: &str) -> String {
    format!("{base}_opt({doc_var}, \"{name}\")")
}

/// Build the `from_document` extraction expression for a sub-typed field,
/// calling the generated `from_struct`. `is_list` selects Array (a list of
/// structs) vs Group (a single struct).
fn sub_type_extraction(sub: &str, name: &str, doc_var: &str, is_list: bool) -> String {
    let arm = if is_list {
        format!(
            "Some(Kind::ListValue(list)) => Some(\
                list.values.iter()\
                    .filter_map(|v| match &v.kind {{\
                        Some(Kind::StructValue(s)) => Some({sub}::from_struct(s)),\
                        _ => None,\
                    }})\
                    .collect::<Vec<_>>()\
            ),"
        )
    } else {
        format!("Some(Kind::StructValue(s)) => Some({sub}::from_struct(s)),")
    };

    format!(
        "{doc_var}.fields.as_ref()\
        .and_then(|f| f.fields.get(\"{name}\"))\
        .and_then(|v| match &v.kind {{ {arm} _ => None, }})"
    )
}

/// Top-level select/radio-with-options: decode string(s) and wrap in the
/// generated enum's `From<String>` so the value matches the enum-typed field.
fn enum_extraction(enum_name: &str, doc_var: &str, name: &str, has_many: bool) -> String {
    if !has_many {
        return format!("get_str_opt({doc_var}, \"{name}\").map({enum_name}::from)");
    }

    let mapped = format!(
        "get_str_list({doc_var}, \"{name}\").into_iter().map({enum_name}::from).collect::<Vec<_>>()"
    );

    format!("{{ let v = {mapped}; if v.is_empty() {{ None }} else {{ Some(v) }} }}")
}

/// Nested (sub-field) select/radio-with-options — same as [`enum_extraction`]
/// but reading from a `DataMap` (`s`) instead of a `Document`.
fn enum_sub_extraction(enum_name: &str, name: &str, has_many: bool) -> String {
    if has_many {
        return format!(
            "s.fields.get(\"{name}\").and_then(|v| match &v.kind {{ {STR_LIST}, _ => None }})\
             .map(|l| l.into_iter().map({enum_name}::from).collect())"
        );
    }

    format!(
        "s.fields.get(\"{name}\").and_then(|v| match &v.kind {{ Some(Kind::StringValue(s)) => Some(s.clone()), _ => None }})\
         .map({enum_name}::from)"
    )
}

/// The match arms decoding a proto value into a polymorphic enum: a bare id
/// string → `Id`, a `{collection, ...}` struct → the matching document variant
/// (via the target's `from_document`). Shared by the top-level and nested paths.
fn poly_arms(poly_name: &str, targets: &[&str]) -> String {
    let mut variants = String::new();
    for t in targets {
        let variant = idents::rust_type(&to_pascal_case(t));
        let slug = idents::escape_str(t);
        wraw!(
            variants,
            "Some(\"{slug}\") => Some({poly_name}::Doc({poly_name}Ref::{variant}(Box::new({variant}::from_document(&__doc))))), "
        );
    }
    format!(
        "Some(Kind::StringValue(s)) if !s.is_empty() => Some({poly_name}::Id(s.clone())), \
         Some(Kind::StructValue(m)) => {{ \
             let __coll = m.fields.get(\"collection\").and_then(|v| match &v.kind {{ Some(Kind::StringValue(s)) => Some(s.as_str()), _ => None }}); \
             let __doc = struct_to_document(m); \
             match __coll {{ {variants}_ => None, }} \
         }},"
    )
}

/// A polymorphic-relationship extraction. `getter` is an `Option<&FieldValue>`
/// expression naming the field's value in the current context (top-level or
/// nested). Has-one is `Option<Poly>`; has-many is `Option<Vec<Poly>>`.
fn poly_extraction(poly_name: &str, targets: &[&str], getter: &str, has_many: bool) -> String {
    let arms = poly_arms(poly_name, targets);

    if has_many {
        return format!(
            "{getter}.and_then(|v| match &v.kind {{ Some(Kind::ListValue(l)) => Some(l.values.iter().filter_map(|v| match &v.kind {{ {arms} _ => None }}).collect::<Vec<_>>()), _ => None }})"
        );
    }

    format!("{getter}.and_then(|v| match &v.kind {{ {arms} _ => None }})")
}

/// Decode a top-level field, reading from a `Document` (`doc_var`). Dispatches on
/// the SHARED [`resolve_ty`] so this generator and `client/rust.rs` can never
/// disagree about a field's type — the whole class of proto↔client drift. Every
/// field decodes to an `Option`, matching the client structs: a draft may lack
/// required values, and field read access and `select` leave keys out.
fn field_extraction(field: &FieldDefinition, parent_pascal: &str, doc_var: &str) -> String {
    let name = &field.name;

    match &resolve_ty(field, parent_pascal) {
        // Strings (incl. id-string relationships: empty-collection upload / no target).
        FieldTy::Str
        | FieldTy::Literal(_)
        | FieldTy::Rel {
            target: None,
            many: false,
        } => scalar("get_str", doc_var, name),
        FieldTy::StrList
        | FieldTy::Rel {
            target: None,
            many: true,
        } => opt_list("get_str_list", doc_var, name),
        FieldTy::Num => scalar("get_num", doc_var, name),
        FieldTy::Int => scalar("get_int", doc_var, name),
        FieldTy::Bool => scalar("get_bool", doc_var, name),
        FieldTy::NumList => opt_list("get_num_list", doc_var, name),
        // Shapeless JSON — a `json` field, a JSON rich text document, an empty
        // group, a blocks/join list — arrives as a structured wire value.
        FieldTy::Json | FieldTy::Map => format!("get_json({doc_var}, \"{name}\")"),
        FieldTy::JsonList => format!("get_json_list({doc_var}, \"{name}\")"),
        // `resolve_ty` never produces the `locale = "all"` shape; the decoders
        // target the single-locale structs.
        FieldTy::Localized(_) => COMPLEX_FALLBACK.to_string(),

        // Typed relationship/upload — `get_rel(_list)` decode both the id string
        // and the populated document; `T` is inferred from the struct field type.
        FieldTy::Rel {
            target: Some(_),
            many: true,
        } => opt_list("get_rel_list", doc_var, name),
        FieldTy::Rel {
            target: Some(_),
            many: false,
        } => format!("get_rel({doc_var}, \"{name}\")"),

        FieldTy::PolyRel {
            name: pn,
            targets,
            many,
        } => poly_extraction(
            &idents::rust_type(pn),
            &targets.iter().map(String::as_str).collect::<Vec<_>>(),
            &format!("{doc_var}.fields.as_ref().and_then(|f| f.fields.get(\"{name}\"))"),
            *many,
        ),
        FieldTy::Enum { name: en, many, .. } => {
            enum_extraction(&idents::rust_type(en), doc_var, name, *many)
        }
        FieldTy::SubType { name: sn, list } => {
            sub_type_extraction(&idents::rust_type(sn), name, doc_var, *list)
        }
    }
}

/// The `locale = "all"` read shape has no counterpart in the single-locale
/// structs, so it decodes to `None`.
const COMPLEX_FALLBACK: &str = "None /* complex field */";

/// Render a `from_struct` impl for an array/group sub-type. `pascal` is the
/// sub-type's unsanitized compound name (e.g. `PostsItems`) — the impl is for
/// its [`idents::rust_type`] — threaded into
/// [`sub_field_extraction`] so a nested group/array references the right
/// nested sub-type name. `row_id` reads the junction `id` a relational array
/// row carries.
fn render_sub_type_from_struct(
    out: &mut String,
    pascal: &str,
    fields: &[FieldDefinition],
    row_id: bool,
) {
    w!(out, "impl {} {{", idents::rust_type(pascal));
    w!(out, "    fn from_struct(s: &DataMap) -> Self {{");
    w!(out, "        Self {{");

    if row_id {
        w!(
            out,
            "            id: s.fields.get(\"id\").and_then(|v| match &v.kind {{ Some(Kind::StringValue(s)) => Some(s.clone()), _ => None }}),"
        );
    }

    // Flatten layout wrappers exactly like `render_field_extractions` and the
    // client struct-definition side — a Row/Collapsible/Tabs nested inside an
    // array/group otherwise reaches `resolve_ty` and panics.
    for f in flatten_array_sub_fields(fields) {
        let extraction = sub_field_extraction(f, pascal);
        w!(
            out,
            "            {}: {},",
            idents::rust_field(&f.name).ident,
            extraction
        );

        for column in f.companion_columns(&f.name) {
            let ident = idents::rust_field(&column).ident;
            w!(
                out,
                "            {ident}: s.fields.get(\"{column}\").and_then(|v| match &v.kind {{ Some(Kind::StringValue(s)) => Some(s.clone()), _ => None }}),"
            );
        }
    }

    w!(out, "        }}");
    w!(out, "    }}");
    w!(out, "}}");
    w!(out, "");
}

/// Match arm decoding a `ListValue` of strings into a `Vec<String>` (a
/// `has_many` scalar sub-field, an options-less select/radio, or an
/// empty-collection upload).
const STR_LIST: &str = "Some(Kind::ListValue(l)) => Some(l.values.iter().filter_map(|v| match &v.kind { Some(Kind::StringValue(s)) => Some(s.clone()), _ => None }).collect())";

/// The nested match arm decoding a typed relationship into `Rel<T>`: an id string
/// (`Rel::Id`) or a populated document (`Rel::Doc` via `struct_to_document` +
/// `from_document`). `has_many` wraps the per-element form in a list decode.
fn nested_rel_arm(t: &str, has_many: bool) -> String {
    let one = format!(
        "Some(Kind::StringValue(s)) if !s.is_empty() => Some(Rel::Id(s.clone())), Some(Kind::StructValue(m)) => Some(Rel::Doc(Box::new({t}::from_document(&struct_to_document(m)))))"
    );
    if has_many {
        format!(
            "Some(Kind::ListValue(l)) => Some(l.values.iter().filter_map(|v| match &v.kind {{ {one}, _ => None }}).collect())"
        )
    } else {
        one
    }
}

/// Extraction for a sub-type field, reading from a nested `DataMap` (`s`).
///
/// Mirrors the Rust client printer's (`super::client::rust`) type mapping so the
/// decoded value's type matches the generated struct field: `has_many` scalars →
/// `Vec`, select/radio-with-options → the generated enum via `From<String>`,
/// relationships/uploads → `Rel<T>` / `Vec<Rel<T>>`, polymorphic → the generated
/// discriminated enum, empty-collection uploads → `String` / `Vec<String>`, and a
/// nested group/array → the child sub-type via its own `from_struct`.
/// `parent_pascal` is the enclosing sub-type's compound name. Every sub-field
/// decodes to an `Option`, matching the client sub-types.
fn sub_field_extraction(field: &FieldDefinition, parent_pascal: &str) -> String {
    let name = &field.name;

    // An `Option<T>` reading `s.fields[name]` through the match arm `arm`.
    let get = |arm: &str| {
        format!("s.fields.get(\"{name}\").and_then(|v| match &v.kind {{ {arm}, _ => None }})")
    };

    match &resolve_ty(field, parent_pascal) {
        // Strings (incl. id-string relationships: empty-collection upload / no target).
        FieldTy::Str
        | FieldTy::Literal(_)
        | FieldTy::Rel {
            target: None,
            many: false,
        } => get("Some(Kind::StringValue(s)) => Some(s.clone())"),
        FieldTy::StrList
        | FieldTy::Rel {
            target: None,
            many: true,
        } => get(STR_LIST),
        FieldTy::Num => get(
            "Some(Kind::IntValue(n)) => Some(*n as f64), Some(Kind::DoubleValue(n)) => Some(*n)",
        ),
        FieldTy::Int => get("Some(Kind::IntValue(n)) => Some(*n)"),
        FieldTy::Bool => get("Some(Kind::BoolValue(b)) => Some(*b)"),
        FieldTy::NumList => get(
            "Some(Kind::ListValue(l)) => Some(l.values.iter().filter_map(|v| match &v.kind { Some(Kind::IntValue(n)) => Some(*n as f64), Some(Kind::DoubleValue(n)) => Some(*n), _ => None }).collect())",
        ),
        // Shapeless JSON — a `json` field, a JSON rich text document, an empty
        // group, nested blocks — arrives as a structured wire value.
        FieldTy::Json | FieldTy::Map => {
            format!("s.fields.get(\"{name}\").map(field_value_to_json)")
        }
        FieldTy::JsonList => get(
            "Some(Kind::ListValue(l)) => Some(l.values.iter().map(field_value_to_json).collect())",
        ),
        // `resolve_ty` never produces the `locale = "all"` shape; the decoders
        // target the single-locale structs.
        FieldTy::Localized(_) => COMPLEX_FALLBACK.to_string(),

        // Typed relationship — id string OR populated document. Decoding the
        // `StructValue` form is what closes the nested-populated-relationship gap.
        FieldTy::Rel {
            target: Some(t),
            many,
        } => get(&nested_rel_arm(&idents::rust_type(t), *many)),

        FieldTy::PolyRel {
            name: pn,
            targets,
            many,
        } => poly_extraction(
            &idents::rust_type(pn),
            &targets.iter().map(String::as_str).collect::<Vec<_>>(),
            &format!("s.fields.get(\"{name}\")"),
            *many,
        ),
        FieldTy::Enum { name: en, many, .. } => {
            enum_sub_extraction(&idents::rust_type(en), name, *many)
        }

        FieldTy::SubType {
            name: sn,
            list: false,
        } => {
            let sub = idents::rust_type(sn);
            get(&format!(
                "Some(Kind::StructValue(m)) => Some({sub}::from_struct(m))"
            ))
        }
        FieldTy::SubType {
            name: sn,
            list: true,
        } => {
            let sub = idents::rust_type(sn);
            get(&format!(
                "Some(Kind::ListValue(l)) => Some(l.values.iter().filter_map(|v| match &v.kind {{ Some(Kind::StructValue(m)) => Some({sub}::from_struct(m)), _ => None }}).collect())"
            ))
        }
    }
}

