    /// One generated `export interface` block, from its header to its closing brace.
    fn interface_block<'a>(out: &'a str, header: &str) -> &'a str {
        let start = out
            .find(header)
            .unwrap_or_else(|| panic!("{header} not emitted:\n{out}"));
        let rest = &out[start..];

        &rest[..rest.find("\n}").map_or(rest.len(), |i| i + 2)]
    }

    /// A read document may lack any field — a draft may miss required values,
    /// and field read access and `select` leave keys out — so every field of
    /// the document, and of its sub-types, is optional. The create input keeps
    /// its required fields, nested ones included: its sub-types are the `…Data`
    /// variants.
    #[test]
    fn typescript_read_document_fields_are_optional() {
        let col = make_col(
            "posts",
            vec![
                text_field("title", true),
                FieldDefinition::builder("seo", FieldType::Group)
                    .fields(vec![text_field("meta_title", true)])
                    .build(),
            ],
        );
        let mut out = String::new();
        render_collection(&mut out, &col);

        let doc = interface_block(&out, "export interface PostsDocument {");
        assert!(doc.contains("  title?: string | null;"), "{doc}");
        assert!(doc.contains("  seo?: PostsSeo | null;"), "{doc}");

        let seo = interface_block(&out, "export interface PostsSeo {");
        assert!(seo.contains("  meta_title?: string | null;"), "{seo}");

        let data = interface_block(&out, "export interface PostsData {");
        assert!(data.contains("  title: string;"), "{data}");
        assert!(data.contains("  seo?: PostsSeoData;"), "{data}");
        assert!(out.contains("/** Input data for creating a Posts"), "{out}");

        let seo_input = interface_block(&out, "export interface PostsSeoData {");
        assert!(seo_input.contains("  meta_title: string;"), "{seo_input}");
    }

