/// Emits TypeScript type definitions.
pub(super) struct TsPrinter {
    w: CodeWriter,
}

impl TsPrinter {
    pub(super) fn new() -> Self {
        Self {
            w: CodeWriter::new("  "),
        }
    }

    /// Emit a read document: `id`, every field optional and nullable, then the
    /// stored system keys and timestamps.
    fn read_interface(&mut self, name: &str, def: &Document) {
        let (fields, system, timestamps) = (&def.fields, &def.system, def.timestamps);

        self.interface(name, |w| {
            w.line("id: string;");
            for f in fields.iter().chain(system) {
                emit_read_field(w, f);
            }
            if timestamps {
                w.line("created_at?: string;");
                w.line("updated_at?: string;");
            }
        });
    }

    /// Emit `export interface NAME { <body> }` followed by a blank line.
    fn interface(&mut self, name: &str, body: impl FnOnce(&mut CodeWriter)) {
        self.w
            .block(&format!("export interface {name} {{"), "}", body);
        self.w.blank();
    }
}

impl ClientPrinter for TsPrinter {
    fn prelude(&mut self) {
        self.w.line("// Auto-generated by crap-cms. Do not edit.");
        self.w.blank();
        self.w.line(
            "/** A localized field read with `locale = \"all\"`: one value per locale code, `null` where a locale has none. */",
        );
        self.w
            .line("export type Localized<T> = { [locale: string]: T | null };");
        self.w.blank();
    }

    /// A sub-type's input variant (`…Data`, its required fields kept) and its
    /// read type, whose every field is optional and nullable.
    fn sub_type(&mut self, def: &SubType) {
        let name = idents::ts_type(&def.name);
        let fields = &def.fields;

        if !def.read_only {
            self.interface(&format!("{name}Data"), |w| {
                for f in fields {
                    emit_input_field(w, f);
                }
            });
        }

        self.interface(&name, |w| {
            for f in fields {
                emit_read_field(w, f);
            }
        });
    }

    fn document(&mut self, def: &Document) {
        let pascal = idents::ts_type(&def.name);

        if def.localized {
            self.w.line(&format!(
                "/** {pascal} read with `locale = \"all\"`: localized fields hold one value per locale */"
            ));
            self.read_interface(&format!("{pascal}LocalizedDocument"), def);
            return;
        }

        let data_doc = if def.is_global {
            format!("/** Input data for the {pascal} global; an update accepts any subset */")
        } else {
            format!(
                "/** Input data for creating a {pascal}; an update accepts any subset (`Partial<{pascal}Data>`) */"
            )
        };
        self.w.line(&data_doc);
        let fields = &def.fields;
        self.interface(&format!("{pascal}Data"), |w| {
            for f in fields {
                emit_input_field(w, f);
            }
        });

        let doc_doc = if def.is_global {
            format!("/** {pascal} global document */")
        } else {
            format!("/** {pascal} document returned from the API */")
        };
        self.w.line(&doc_doc);
        self.read_interface(&format!("{pascal}Document"), def);
    }

    // Select/radio narrowing and polymorphic unions are inlined at each use site.
    fn enum_types(&mut self, _defs: &[EnumDef]) {}

    fn poly_types(&mut self, _defs: &[PolyDef]) {}

    fn epilogue(&mut self, registry: &Registry) {
        let slugs = sorted_collection_slugs(registry);
        if slugs.is_empty() {
            return;
        }
        let union = slugs
            .iter()
            .map(|s| format!("\"{s}\""))
            .collect::<Vec<_>>()
            .join(" | ");
        self.w.line("/** All collection slugs */");
        self.w
            .line(&format!("export type CollectionSlug = {union};"));
    }

    fn finish(self: Box<Self>) -> String {
        self.w.finish()
    }
}

/// Emit one read property: optional, and `null` where the stored value is
/// empty.
fn emit_read_field(w: &mut CodeWriter, field: &Field) {
    emit_property(w, field, true, &format!("{} | null", ts_ty(&field.ty)));
}

/// Emit one input property: its own optionality, and a nested sub-type as its
/// input variant.
fn emit_input_field(w: &mut CodeWriter, field: &Field) {
    emit_property(w, field, field.optional, &input_ty(&field.ty));
}

/// Emit one interface property: an optional polymorphic-target `JSDoc` comment,
/// then `key?: type;` (`?` when `optional`).
fn emit_property(w: &mut CodeWriter, field: &Field, optional: bool, ty: &str) {
    if let FieldTy::PolyRel { targets, .. } = &field.ty {
        w.line(&format!(
            "/** Polymorphic relationship — targets: {} */",
            targets.join(", ")
        ));
    }
    let opt = if optional { "?" } else { "" };
    w.line(&format!("{}{opt}: {ty};", idents::ts_key(&field.name)));
}

/// The TypeScript type of an input value: a sub-type is its `…Data` variant.
fn input_ty(ty: &FieldTy) -> String {
    let FieldTy::SubType { name, list } = ty else {
        return ts_ty(ty);
    };

    let n = format!("{}Data", idents::ts_type(name));
    if *list { format!("{n}[]") } else { n }
}

/// Map a [`FieldTy`] to its TypeScript type string.
fn ts_ty(ty: &FieldTy) -> String {
    match ty {
        FieldTy::Str => "string".to_string(),
        FieldTy::Num => "number".to_string(),
        FieldTy::Bool => "boolean".to_string(),
        FieldTy::Json => "unknown".to_string(),
        FieldTy::Map => "Record<string, unknown>".to_string(),
        FieldTy::StrList => "string[]".to_string(),
        FieldTy::NumList => "number[]".to_string(),
        FieldTy::JsonList => "Record<string, unknown>[]".to_string(),
        // A typed relationship is an id string OR a populated document (the API's
        // `depth` controls which), so it unions the id with the target's
        // `Document` type. Polymorphic / empty-target relationships (`None`)
        // have no known type and stay plain id strings.
        FieldTy::Rel {
            target: Some(t),
            many,
        } => {
            let doc = format!("{}Document", idents::ts_type(t));
            if *many {
                format!("(string | {doc})[]")
            } else {
                format!("string | {doc}")
            }
        }
        FieldTy::Rel { target: None, many } => {
            if *many {
                "string[]".to_string()
            } else {
                "string".to_string()
            }
        }
        // A polymorphic relationship is an id string OR one of the target docs
        // (populated at depth>=1), so it unions the id with every target's Document.
        FieldTy::PolyRel { targets, many, .. } => {
            let mut parts = vec!["string".to_string()];
            parts.extend(
                targets
                    .iter()
                    .map(|t| format!("{}Document", idents::ts_type(&to_pascal_case(t)))),
            );
            let base = parts.join(" | ");
            if *many { format!("({base})[]") } else { base }
        }
        FieldTy::SubType { name, list } => {
            let n = idents::ts_type(name);
            if *list { format!("{n}[]") } else { n }
        }
        FieldTy::Localized(inner) => format!("Localized<{}>", ts_ty(inner)),
        FieldTy::Enum { values, many, .. } => {
            let base = values
                .iter()
                .map(|v| format!("\"{}\"", idents::escape_str(v)))
                .collect::<Vec<_>>()
                .join(" | ");
            if *many { format!("({base})[]") } else { base }
        }
    }
}

