//! Rust `ClientPrinter` — structs with serde derives and a populated-or-id
//! `Rel<T>` for gRPC clients.

use std::collections::HashSet;

use crate::{
    core::Registry,
    typegen::{
        helpers::{sorted_collection_slugs, to_pascal_case},
        idents,
    },
};

use super::{
    ClientPrinter, Document, EnumDef, Field, FieldTy, PolyDef, SubType, writer::CodeWriter,
};

/// Emits Rust type definitions.
pub(super) struct RustPrinter {
    w: CodeWriter,
}

impl RustPrinter {
    pub(super) fn new() -> Self {
        Self {
            w: CodeWriter::new("    "),
        }
    }

    /// Emit the `#[derive(...)]` + `pub struct NAME { ... }` shell, running
    /// `body` for the struct's fields.
    fn struct_def(&mut self, name: &str, body: impl FnOnce(&mut CodeWriter)) {
        self.w
            .line("#[derive(Debug, Clone, Serialize, Deserialize)]");
        let header = format!("pub struct {} {{", idents::rust_type(name));
        self.w.block(&header, "}", body);
        self.w.blank();
    }
}

impl ClientPrinter for RustPrinter {
    fn prelude(&mut self) {
        let w = &mut self.w;
        w.line("// Auto-generated by crap-cms. Do not edit.");
        w.blank();
        w.line("use serde::{Deserialize, Serialize};");
        w.blank();

        w.line("/// A relationship field: either an ID string (depth=0)");
        w.line("/// or a populated document (depth>=1).");
        w.line("#[derive(Debug, Clone, Serialize, Deserialize)]");
        w.line("#[serde(untagged)]");
        w.block("pub enum Rel<T> {", "}", |w| {
            w.line("Doc(Box<T>),");
            w.line("Id(String),");
        });
        w.blank();
        w.block("impl<T> Rel<T> {", "}", |w| {
            w.line("/// Get the ID if unpopulated.");
            w.block("pub fn as_id(&self) -> Option<&str> {", "}", |w| {
                w.line("match self { Rel::Id(id) => Some(id), _ => None }");
            });
            w.blank();
            w.line("/// Get the populated document.");
            w.block("pub fn as_doc(&self) -> Option<&T> {", "}", |w| {
                w.line("match self { Rel::Doc(d) => Some(d), _ => None }");
            });
        });
        w.blank();
    }

    // Rust emits read types only; a write-shape sub-type has nothing to render.
    fn sub_type(&mut self, def: &SubType) {
        if def.input {
            return;
        }

        let fields = &def.fields;
        self.struct_def(&def.name, |w| {
            for f in fields {
                emit_field(w, f);
            }
        });
    }

    fn document(&mut self, def: &Document) {
        let name = if def.localized {
            self.w.line(&format!(
                "/// The `{}` document read with `locale = \"all\"`: localized fields hold one value per locale.",
                def.slug
            ));
            format!("{}Localized", def.name)
        } else {
            def.name.clone()
        };
        // The populated `collection` tag is not a member: the polymorphic enums
        // consume it as their serde tag, and a single-target `Rel<T>` already
        // knows its collection.
        let (fields, system, timestamps) = (&def.fields, &def.system, def.timestamps);

        self.struct_def(&name, |w| {
            w.line("pub id: String,");
            for f in fields.iter().chain(system) {
                emit_field(w, f);
            }
            if timestamps {
                for col in ["created_at", "updated_at"] {
                    w.line("#[serde(skip_serializing_if = \"Option::is_none\")]");
                    w.line(&format!("pub {col}: Option<String>,"));
                }
            }
        });
    }

    fn enum_types(&mut self, defs: &[EnumDef]) {
        for def in defs {
            emit_enum(&mut self.w, def);
        }
    }

    fn poly_types(&mut self, defs: &[PolyDef]) {
        for def in defs {
            emit_poly(&mut self.w, def);
        }
    }

    fn epilogue(&mut self, registry: &Registry) {
        let slugs = sorted_collection_slugs(registry);
        if slugs.is_empty() {
            return;
        }
        self.w.line("/// All collection slugs.");
        self.w
            .line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]");
        self.w.block("pub enum CollectionSlug {", "}", |w| {
            for slug in slugs {
                w.line(&format!("#[serde(rename = \"{slug}\")]"));
                w.line(&format!("{},", idents::rust_type(&to_pascal_case(slug))));
            }
        });
        self.w.blank();
    }

    fn finish(self: Box<Self>) -> String {
        self.w.finish()
    }
}

/// Emit one read field — every field is optional on read: an optional
/// polymorphic-target comment, a combined `#[serde(...)]` line (rename and
/// skip), then the `pub ident: Option<Type>,`.
fn emit_field(w: &mut CodeWriter, field: &Field) {
    if let FieldTy::PolyRel { targets, .. } = &field.ty {
        w.line(&format!(
            "/// Polymorphic relationship — targets: {}",
            targets.join(", ")
        ));
    }
    let ty = rust_ty(&field.ty);
    let f = idents::rust_field(&field.name);

    let mut serde_parts: Vec<String> = Vec::new();
    if let Some(wire) = &f.rename {
        serde_parts.push(format!("rename = \"{wire}\""));
    }
    serde_parts.push("skip_serializing_if = \"Option::is_none\"".to_string());
    w.line(&format!("#[serde({})]", serde_parts.join(", ")));

    w.line(&format!("pub {}: Option<{ty}>,", f.ident));
}

/// Map a [`FieldTy`] to its Rust type string.
fn rust_ty(ty: &FieldTy) -> String {
    match ty {
        // A literal set stays a plain `String`, as the proto decoder reads it.
        FieldTy::Str | FieldTy::Literal(_) => "String".to_string(),
        FieldTy::Num => "f64".to_string(),
        FieldTy::Bool => "bool".to_string(),
        FieldTy::Json | FieldTy::Map => "serde_json::Value".to_string(),
        FieldTy::StrList => "Vec<String>".to_string(),
        FieldTy::NumList => "Vec<f64>".to_string(),
        FieldTy::JsonList => "Vec<serde_json::Value>".to_string(),
        FieldTy::Rel {
            target: Some(t),
            many,
        } => {
            let t = idents::rust_type(t);
            if *many {
                format!("Vec<Rel<{t}>>")
            } else {
                format!("Rel<{t}>")
            }
        }
        // Polymorphic / empty-target relationships are id strings.
        FieldTy::Rel { target: None, many } => {
            if *many {
                "Vec<String>".to_string()
            } else {
                "String".to_string()
            }
        }
        // Select/radio and polymorphic relationships each reference a generated
        // named type (emitted by `enum_types` / `poly_types`).
        FieldTy::Enum { name, many, .. } | FieldTy::PolyRel { name, many, .. } => {
            let n = idents::rust_type(name);
            if *many { format!("Vec<{n}>") } else { n }
        }
        FieldTy::SubType { name, list } => {
            let n = idents::rust_type(name);
            if *list { format!("Vec<{n}>") } else { n }
        }
        // A locale without a value reads as `null`.
        FieldTy::Localized(inner) => {
            format!(
                "std::collections::HashMap<String, Option<{}>>",
                rust_ty(inner)
            )
        }
    }
}

/// Emit a lossless select/radio enum: named variants for the known values plus
/// an `Other(String)` catch-all, wired through `#[serde(from/into)]` so an
/// unrecognized value (e.g. an option removed since generation) round-trips as
/// `Other(value)` instead of failing to deserialize.
fn emit_enum(w: &mut CodeWriter, def: &EnumDef) {
    let type_name = idents::rust_type(&def.name);

    // A unique variant identifier per value; `Other` is reserved for the catch-all.
    let mut seen = HashSet::new();
    seen.insert("Other".to_string());
    let variants: Vec<(String, &str)> = def
        .values
        .iter()
        .map(|v| {
            // `rust_type` applies the reserved-name guard (a value `"self"` →
            // variant `Self` would be rejected); `variant_ident` already
            // handled digits.
            let ident = idents::rust_type(&idents::variant_ident(v));
            (idents::dedup(ident, &mut seen), v.as_str())
        })
        .collect();

    w.line("/// Select/radio field values. An unrecognized value (e.g. an option");
    w.line("/// removed since generation) is preserved in `Other`, never rejected.");
    w.line("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]");
    w.line("#[serde(from = \"String\", into = \"String\")]");
    w.block(&format!("pub enum {type_name} {{"), "}", |w| {
        for (variant, _) in &variants {
            w.line(&format!("{variant},"));
        }
        w.line("Other(String),");
    });
    w.blank();

    w.block(&format!("impl From<String> for {type_name} {{"), "}", |w| {
        w.block("fn from(s: String) -> Self {", "}", |w| {
            w.block("match s.as_str() {", "}", |w| {
                for (variant, value) in &variants {
                    w.line(&format!(
                        "\"{}\" => {type_name}::{variant},",
                        idents::escape_str(value)
                    ));
                }
                w.line(&format!("_ => {type_name}::Other(s),"));
            });
        });
    });
    w.blank();

    w.block(&format!("impl From<{type_name}> for String {{"), "}", |w| {
        w.block(&format!("fn from(v: {type_name}) -> Self {{"), "}", |w| {
            w.block("match v {", "}", |w| {
                for (variant, value) in &variants {
                    w.line(&format!(
                        "{type_name}::{variant} => \"{}\".to_string(),",
                        idents::escape_str(value)
                    ));
                }
                w.line(&format!("{type_name}::Other(s) => s,"));
            });
        });
    });
    w.blank();
}

/// Emit a polymorphic relationship's type: an untagged wrapper that is either
/// an id string or a populated document, with the document side an internally
/// `collection`-tagged enum over the target types. Sound at every depth — the
/// composite `"collection/id"` string decodes to `Id`, the `{collection, ...}`
/// object at depth>=1 decodes to the matching document variant.
fn emit_poly(w: &mut CodeWriter, def: &PolyDef) {
    let wrapper = idents::rust_type(&def.name);
    let doc_enum = format!("{wrapper}Ref");

    w.line("/// A polymorphic relationship: an id string, or one of the target");
    w.line("/// documents (populated at depth>=1), keyed by the `collection` field.");
    w.line("#[derive(Debug, Clone, Serialize, Deserialize)]");
    w.line("#[serde(untagged)]");
    w.block(&format!("pub enum {wrapper} {{"), "}", |w| {
        w.line(&format!("Doc({doc_enum}),"));
        w.line("Id(String),");
    });
    w.blank();

    w.line("#[derive(Debug, Clone, Serialize, Deserialize)]");
    w.line("#[serde(tag = \"collection\")]");
    w.block(&format!("pub enum {doc_enum} {{"), "}", |w| {
        for target in &def.targets {
            let struct_name = idents::rust_type(&to_pascal_case(target));
            w.line(&format!(
                "#[serde(rename = \"{}\")]",
                idents::escape_str(target)
            ));
            w.line(&format!("{struct_name}(Box<{struct_name}>),"));
        }
    });
    w.blank();
}

