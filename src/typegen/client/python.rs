/// Emits Python type definitions.
pub(super) struct PyPrinter {
    w: CodeWriter,
}

impl PyPrinter {
    pub(super) fn new() -> Self {
        Self {
            w: CodeWriter::new("    "),
        }
    }

    /// Emit `@dataclass` + `class NAME:` with `body`, then a blank line.
    fn class(&mut self, name: &str, body: impl FnOnce(&mut CodeWriter)) {
        self.w.line("@dataclass");
        self.w.block(&format!("class {name}:"), "", body);
        // A dataclass body's dedent needs no closer, but the trailing blank
        // line separates it from the next definition.
    }
}

impl ClientPrinter for PyPrinter {
    fn prelude(&mut self) {
        let w = &mut self.w;
        w.line("# Auto-generated by crap-cms. Do not edit.");
        w.blank();
        w.line("from __future__ import annotations");
        w.line("from dataclasses import dataclass, field");
        w.line("from typing import Optional, Any, Literal");
        w.blank();
    }

    fn sub_type(&mut self, def: &SubType) {
        let name = idents::python_class(&def.name);
        let fields = &def.fields;
        self.class(&name, |w| {
            emit_fields_required_first(w, fields);
        });
    }

    fn document(&mut self, def: &Document) {
        let name = idents::python_class(&def.name);
        let comment = select_options_docstring(&def.select_options);
        let fields = &def.fields;
        let timestamps = def.timestamps;

        self.class(&name, |w| {
            if !comment.is_empty() {
                w.line(&format!("\"\"\"{comment}\"\"\""));
            }
            w.line("id: str = \"\"");
            emit_fields_required_first(w, fields);
            if timestamps {
                w.line("created_at: Optional[str] = None");
                w.line("updated_at: Optional[str] = None");
            }
        });
    }

    // Select/radio narrowing and polymorphic unions are inlined at each use site.
    fn enum_types(&mut self, _defs: &[EnumDef]) {}

    fn poly_types(&mut self, _defs: &[PolyDef]) {}

    fn epilogue(&mut self, registry: &Registry) {
        let slugs = sorted_collection_slugs(registry);
        if slugs.is_empty() {
            return;
        }
        let members = slugs
            .iter()
            .map(|s| format!("\"{}\"", idents::escape_str(s)))
            .collect::<Vec<_>>()
            .join(", ");
        self.w.line("# All collection slugs.");
        self.w.line(&format!("CollectionSlug = Literal[{members}]"));
    }

    fn finish(self: Box<Self>) -> String {
        self.w.finish()
    }
}

/// Emit required (no-default-risk) fields before optional ones — a dataclass
/// requires non-defaulted fields first, and it reads better regardless.
fn emit_fields_required_first(w: &mut CodeWriter, fields: &[Field]) {
    for f in fields.iter().filter(|f| !f.optional) {
        emit_field(w, f);
    }
    for f in fields.iter().filter(|f| f.optional) {
        emit_field(w, f);
    }
}

/// Emit one dataclass attribute: an optional polymorphic-target comment, then
/// `attr: type = default`, noting the wire key when the attribute was renamed.
fn emit_field(w: &mut CodeWriter, field: &Field) {
    if let FieldTy::PolyRel { targets, .. } = &field.ty {
        w.line(&format!(
            "# Polymorphic relationship — targets: {}",
            targets.join(", ")
        ));
    }

    let py_type = py_ty(&field.ty);
    let (attr, wire) = idents::python_field(field.name);
    let wire_comment = wire.map_or_else(String::new, |w| format!("  # wire: {w}"));

    if field.optional {
        w.line(&format!("{attr}: Optional[{py_type}] = None{wire_comment}"));
    } else {
        w.line(&format!(
            "{attr}: {py_type} = {}{wire_comment}",
            py_default(&field.ty)
        ));
    }
}

/// Map a [`FieldTy`] to its Python type string.
fn py_ty(ty: &FieldTy) -> String {
    match ty {
        FieldTy::Str => "str".to_string(),
        FieldTy::Num => "float".to_string(),
        FieldTy::Bool => "bool".to_string(),
        FieldTy::Json => "Any".to_string(),
        FieldTy::Map => "dict".to_string(),
        FieldTy::StrList => "list[str]".to_string(),
        FieldTy::NumList => "list[float]".to_string(),
        FieldTy::JsonList => "list[dict]".to_string(),
        // A typed relationship is an id string OR a populated document (the API's
        // `depth` controls which), so it unions `str` with the target's class.
        // Polymorphic / empty-target relationships (`None`) stay plain id strings.
        FieldTy::Rel {
            target: Some(t),
            many,
        } => {
            let doc = idents::python_class(t);
            if *many {
                format!("list[str | {doc}]")
            } else {
                format!("str | {doc}")
            }
        }
        FieldTy::Rel { target: None, many } => {
            if *many {
                "list[str]".to_string()
            } else {
                "str".to_string()
            }
        }
        // A polymorphic relationship is an id string OR one of the target docs
        // (populated at depth>=1), so it unions `str` with every target's class.
        FieldTy::PolyRel { targets, many, .. } => {
            let mut parts = vec!["str".to_string()];
            parts.extend(
                targets
                    .iter()
                    .map(|t| idents::python_class(&to_pascal_case(t))),
            );
            let base = parts.join(" | ");
            if *many { format!("list[{base}]") } else { base }
        }
        // Select/radio with options narrow to a `Literal` of the allowed values.
        FieldTy::Enum { values, many, .. } => {
            let lit = format!("Literal[{}]", literal_values(values));
            if *many { format!("list[{lit}]") } else { lit }
        }
        FieldTy::SubType { name, list } => {
            let n = idents::python_class(name);
            if *list { format!("list[{n}]") } else { n }
        }
    }
}

/// The comma-separated, quoted option values inside a `Literal[...]`.
fn literal_values(values: &[String]) -> String {
    values
        .iter()
        .map(|v| format!("\"{}\"", idents::escape_str(v)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The default value for a required field. List-typed fields use an empty-list
/// factory — a `""` default there would annotate a list but construct a string,
/// so `for x in obj.field` would iterate a string's characters. A required
/// `Literal` defaults to its first option so the default is a valid member.
fn py_default(ty: &FieldTy) -> String {
    match ty {
        FieldTy::StrList
        | FieldTy::NumList
        | FieldTy::JsonList
        | FieldTy::SubType { list: true, .. }
        | FieldTy::Rel { many: true, .. }
        | FieldTy::PolyRel { many: true, .. }
        | FieldTy::Enum { many: true, .. } => "field(default_factory=list)".to_string(),
        FieldTy::Num => "0.0".to_string(),
        FieldTy::Bool => "False".to_string(),
        // Non-empty by construction (an `Enum` is only produced when options exist).
        FieldTy::Enum {
            values,
            many: false,
            ..
        } => format!("\"{}\"", idents::escape_str(&values[0])),
        _ => "\"\"".to_string(),
    }
}

/// A docstring summarizing top-level `Select` fields' options, or empty.
fn select_options_docstring(select_options: &[(String, Vec<String>)]) -> String {
    if select_options.is_empty() {
        return String::new();
    }
    // Single-quote the values: this text sits inside a `"""..."""` docstring, so
    // a value ending in `"` next to the closing delimiter would form `""""` and
    // break the parse. Single quotes are literal inside a double-quoted docstring.
    let parts: Vec<String> = select_options
        .iter()
        .map(|(name, values)| {
            let opts = values
                .iter()
                .map(|v| format!("'{v}'"))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{name}: {opts}")
        })
        .collect();
    format!("Select fields — {}", parts.join("; "))
}

