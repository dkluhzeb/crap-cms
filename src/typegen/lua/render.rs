/// Render all Lua type definitions.
///
/// # Errors
///
/// Fails if two schema constructs render the same class or alias name — see
/// [`check_unique_type_names`].
pub(in crate::typegen) fn render(registry: &Registry) -> Result<String> {
    let mut out = String::from("---@meta\n-- Auto-generated by crap-cms. Do not edit.\n\n");

    let mut slugs: Vec<&Slug> = registry.collections.keys().collect();
    slugs.sort();
    for slug in slugs {
        let col = &registry.collections[slug];
        render_collection(&mut out, col);
    }

    let mut global_slugs: Vec<&Slug> = registry.globals.keys().collect();
    global_slugs.sort();
    for slug in global_slugs {
        let global = &registry.globals[slug];
        render_global(&mut out, global);
    }

    render_find_overloads(&mut out, registry);
    render_template_data_types(&mut out);

    check_unique_type_names(&out)?;

    Ok(out)
}

/// The class or alias name a `---@class` / `---@alias` annotation line
/// declares (after an `(exact)` attribute, before any `: parent`).
fn declared_type_name(line: &str) -> Option<&str> {
    let tag = line.strip_prefix("---")?.trim_start();
    let rest = tag
        .strip_prefix("@class ")
        .or_else(|| tag.strip_prefix("@alias "))?
        .trim_start();
    let rest = rest.strip_prefix("(exact)").map_or(rest, str::trim_start);

    rest.split_whitespace().next()
}

/// Fail if two schema constructs render the same class or alias name. Names
/// are built from `PascalCase`d slugs and field paths, which isn't injective
/// (collections `a1` and `a_1` are both `A1`; a `posts` group `seo_meta` and a
/// `posts_seo` group `meta` are both `PostsSeoMeta`), and `LuaLS` merges two
/// declarations of one name into one type — the second owner's fields would
/// land on the first. Every declaration in the rendered output is checked, so
/// no naming path can slip past.
fn check_unique_type_names(out: &str) -> Result<()> {
    let mut seen = HashSet::new();

    for name in out.lines().filter_map(declared_type_name) {
        ensure!(
            seen.insert(name),
            "generated Lua type `{name}` is declared by two different schema constructs — \
             collection/global slugs or field names that PascalCase to the same name (e.g. \
             collections `a1` and `a_1` are both `A1`, and a `posts` group `seo_meta` and a \
             `posts_seo` group `meta` are both `PostsSeoMeta`). Rename one."
        );
    }

    Ok(())
}

/// Render `crap.template.*` typed shapes and `crap.template_ctx` /
/// `crap.template_data_fn` aliases.
///
/// The template-data context is the same JSON shape every admin page
/// renders. Each Rust typed-context block in `src/admin/context/` has a
/// matching `crap.template.*` class so Lua editors give autocomplete on
/// every level (`ctx.user.email`, `ctx.collection.versions.max_versions`,
/// `ctx.nav.custom_pages[1].icon`, …).
///
/// Per-page extra fields (`collection_cards`, `versions`, …) are not
/// enumerated here — they vary per page and aren't part of the base
/// context. Full per-page shapes live in
/// `docs/src/admin-ui/template-context.md`.
fn render_template_data_types(out: &mut String) {
    out.push_str("-- ─── Template data context (for `crap.template_data.register`) ───\n\n");

    // The annotation for each Rust struct is defined as
    // `impl LuaAnnotation for X` next to the struct itself — see
    // `src/admin/context/*.rs`. Adding a new struct here is one line;
    // changing a field updates the source-of-truth alongside the type.
    CrapMeta::render_lua_annotation(out);
    UserContext::render_lua_annotation(out);
    Breadcrumb::render_lua_annotation(out);
    PageMeta::render_lua_annotation(out);
    NavCollection::render_lua_annotation(out);
    NavGlobal::render_lua_annotation(out);
    NavPage::render_lua_annotation(out);
    NavPageSection::render_lua_annotation(out);
    NavData::render_lua_annotation(out);
    FieldAdminMeta::render_lua_annotation(out);
    FieldMeta::render_lua_annotation(out);
    AdminMeta::render_lua_annotation(out);
    UploadMeta::render_lua_annotation(out);
    VersionsMeta::render_lua_annotation(out);
    AuthMeta::render_lua_annotation(out);
    CollectionContext::render_lua_annotation(out);
    GlobalContext::render_lua_annotation(out);
    DocumentRef::render_lua_annotation(out);
    EditorLocaleOption::render_lua_annotation(out);
    BasePageContext::render_lua_annotation(out);

    out.push_str("---@alias crap.template_data_fn fun(ctx: crap.template_ctx): any\n\n");
}

/// Render typed overload annotations for find/findById/create/update.
fn render_find_overloads(out: &mut String, registry: &Registry) {
    let mut slugs: Vec<&Slug> = registry.collections.keys().collect();
    slugs.sort();

    if slugs.is_empty() {
        return;
    }

    // find() / find_by_id() — emitted as `---@overload`-only blocks
    // with NO `---@param`/`---@return` between overloads. This is
    // the exact shape PR #2838 in lua-language-server targets: when a
    // function has only `@overload`s and no explicit param/return,
    // LuaLS ignores the auto-inferred baseline (nil) and dispatches
    // to the matching overload's return for literal-typed args.
    //
    // Reference test case from the PR:
    //   ---@overload fun(a: 1): string
    //   ---@overload fun(a: 2): number
    //   local function f(a) end
    //   local r = f(1)  -- now narrows to `string`
    //
    // The final `string` overload is the dynamic-slug fallback.
    // Use uniform `crap.FindQuery` as the query type for every
    // overload. LuaLS only narrows `---@overload` reliably when
    // exactly one parameter type varies across the overload set.
    // When `find` had both `collection` (literal `"slug"`) AND
    // `query` (per-collection `crap.query.X`) varying, LuaLS unioned
    // every overload's return at the call site and `result.documents`
    // dissolved into `crap.Document | crap.doc.<every>[]`. Fixing
    // `query` to the base type leaves only the literal `collection`
    // varying — same shape as `find_by_id` — and narrowing kicks in.
    //
    // Users who want per-collection `where` / `order_by` autocomplete
    // can still construct a typed query:
    //   ---@type crap.query.Inquiries
    //   local q = { where = { status = "archived" } }
    //   local r = crap.collections.find("inquiries", q)
    // `crap.query.X` extends `crap.FindQuery`, so the typed variable
    // satisfies the uniform overload slot AND narrows on field
    // access. The result still narrows to `crap.find_result.X`.
    for slug in &slugs {
        let pascal = to_pascal_case(slug);
        w!(
            out,
            "---@overload fun(collection: \"{slug}\", query?: crap.FindQuery): crap.find_result.{pascal}"
        );
    }
    w!(
        out,
        "---@overload fun(collection: string, query?: crap.FindQuery): crap.FindResult"
    );
    w!(out, "function crap.collections.find(collection, query) end");
    out.push('\n');

    for slug in &slugs {
        let pascal = to_pascal_case(slug);
        w!(
            out,
            "---@overload fun(collection: \"{slug}\", id: string, opts?: crap.FindByIdOptions): crap.doc.{pascal}?"
        );
    }
    w!(
        out,
        "---@overload fun(collection: string, id: string, opts?: crap.FindByIdOptions): crap.Document?"
    );
    w!(
        out,
        "function crap.collections.find_by_id(collection, id, opts) end"
    );
    out.push('\n');
}

#[cfg(test)]
mod tests {
    use super::super::test_helpers::text_field;
    use super::*;
    use crate::core::{CollectionDefinition, FieldDefinition, FieldType};

    #[test]
    fn render_sorted_output() {
        let mut registry = Registry::new();
        let mut zebras = CollectionDefinition::new("zebras");
        zebras.timestamps = true;
        registry.register_collection(zebras);
        let mut apples = CollectionDefinition::new("apples");
        apples.timestamps = true;
        registry.register_collection(apples);

        let output = render(&registry).expect("render");
        let apples_pos = output.find("crap.data.Apples").expect("write to String");
        let zebras_pos = output.find("crap.data.Zebras").expect("write to String");
        assert!(apples_pos < zebras_pos);
    }

    #[test]
    fn render_find_overloads_output() {
        let mut registry = Registry::new();
        let mut posts = CollectionDefinition::new("posts");
        posts.timestamps = true;
        posts.fields = vec![text_field("title", true)];
        registry.register_collection(posts);
        let mut pages = CollectionDefinition::new("pages");
        pages.timestamps = true;
        pages.fields = vec![text_field("body", false)];
        registry.register_collection(pages);

        let output = render(&registry).expect("render");
        assert!(output.contains("---@overload fun(collection: \"pages\""));
        assert!(output.contains("---@overload fun(collection: \"posts\""));
        assert!(output.contains("function crap.collections.find(collection, query) end"));
        // find_by_id overloads
        assert!(output.contains(
            "fun(collection: \"posts\", id: string, opts?: crap.FindByIdOptions): crap.doc.Posts?"
        ));
        assert!(output.contains("function crap.collections.find_by_id(collection, id, opts) end"));
    }

    /// Regression: two collections whose slugs `PascalCase` alike (`a1`,
    /// `a_1`) rendered the same classes twice, which `LuaLS` merges silently.
    #[test]
    fn colliding_collection_class_names_are_rejected() {
        let mut registry = Registry::new();
        registry.register_collection(CollectionDefinition::new("a1"));
        registry.register_collection(CollectionDefinition::new("a_1"));

        let err = render(&registry).expect_err("collision").to_string();
        assert!(err.contains("`crap.data.A1`"), "{err}");
    }

    /// A group path and a slug that concatenate to the same sub-type class
    /// collide across owners.
    #[test]
    fn colliding_sub_type_class_names_are_rejected() {
        let group = |name: &str| {
            FieldDefinition::builder(name, FieldType::Group)
                .fields(vec![text_field("x", false)])
                .build()
        };

        let mut posts = CollectionDefinition::new("posts");
        posts.fields = vec![group("seo_meta")];
        let mut posts_seo = CollectionDefinition::new("posts_seo");
        posts_seo.fields = vec![group("meta")];

        let mut registry = Registry::new();
        registry.register_collection(posts);
        registry.register_collection(posts_seo);

        let err = render(&registry).expect_err("collision").to_string();
        assert!(err.contains("`crap.group.PostsSeoMeta`"), "{err}");
    }

    #[test]
    fn declared_type_name_reads_class_and_alias_lines() {
        for (line, name) in [
            ("---@class crap.data.Posts", Some("crap.data.Posts")),
            (
                "---@class (exact) crap.where.Posts",
                Some("crap.where.Posts"),
            ),
            (
                "---@class crap.partial.Posts : crap.partial_many.Posts",
                Some("crap.partial.Posts"),
            ),
            ("--- @class crap.template.Crap", Some("crap.template.Crap")),
            (
                "---@alias crap.hook_fn.Posts fun()",
                Some("crap.hook_fn.Posts"),
            ),
            ("---@field title string", None),
            ("local _coll_posts = {}", None),
        ] {
            assert_eq!(declared_type_name(line), name, "{line}");
        }
    }

    #[test]
    fn render_find_overloads_empty_registry() {
        let registry = Registry::new();
        let output = render(&registry).expect("render");
        assert!(!output.contains("crap.collections.find"));
    }
}
