    w!(out, "---@field name string");
    w!(out, "---@field field_type string");
    w!(out, "---@field required boolean");
    w!(out, "---@field unique boolean");
    w!(out, "---@field localized boolean");
    w!(out, "---@field admin crap.template.field_admin_meta");
